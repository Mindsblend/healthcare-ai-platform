async function seedProducts() {
  for (const product of products) {
    await prisma.product.upsert({
      where: { title: product.title },
      update: {
        slug: generateSlug(product.title),
        description: product.description,
        solution: product.solution,
        price: product.price,
        image: product.image,
        // Nested updates for relations
        icons: {
          deleteMany: {},
          create: product.icons.create,
        },
        gains: {
          deleteMany: {},
          create: product.gains.create,
        },
        faqs: {
          deleteMany: {},
          create: product.faqs.create,
        },
        aiResponses: {
          deleteMany: {},
          create: [
            {
              recommendation: product.aiResponses.create.recommendation,
              explanation: product.aiResponses.create.explanation,
            },
          ],
        },
        category: {
          connect: { id: product.categoryId }, // <-- use product.categoryId
        },
      },
      create: {
        slug: generateSlug(product.title),
        title: product.title,
        description: product.description,
        solution: product.solution,
        price: product.price,
        image: product.image,
        category: {
          connect: { id: product.categoryId }, // <-- use product.categoryId
        },
        icons: { create: product.icons.create },
        gains: { create: product.gains.create },
        faqs: { create: product.faqs.create },
        aiResponses: {
          create: [
            {
              recommendation: product.aiResponses.create.recommendation,
              explanation: product.aiResponses.create.explanation,
            },
          ],
        },
      },
    })
  }
  console.log('✅ Products seeded')
}

